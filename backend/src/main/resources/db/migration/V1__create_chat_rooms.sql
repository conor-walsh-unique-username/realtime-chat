CREATE TABLE chat_rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_chat_rooms_name_length CHECK (char_length(name) BETWEEN 1 AND 80),
    CONSTRAINT ck_chat_rooms_name_trimmed CHECK (name = btrim(name))
);

-- Enforce case-insensitive uniqueness even when two requests arrive together.
CREATE UNIQUE INDEX uq_chat_rooms_name_lower ON chat_rooms (lower(name));
