CREATE TABLE chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES chat_rooms (id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES chat_users (id),
    content VARCHAR(2000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_chat_messages_content_length CHECK (char_length(content) BETWEEN 1 AND 2000)
);

-- Match history queries: choose a room, then read its message IDs backwards.
CREATE INDEX idx_chat_messages_room_id_id ON chat_messages (room_id, id DESC);